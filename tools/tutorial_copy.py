#!/usr/bin/env python3
"""Offline copy generation: canonical route commands embedded in the codelab."""
import argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
BEGIN = '<!-- BEGIN CANONICAL TUTORIAL: generated by tools/tutorial_copy.py -->'
END = '<!-- END CANONICAL TUTORIAL -->'
def render():
    route = (ROOT/'docs/learner-route.md').read_text()
    # Preserve all teaching bytes/commands, only relocate links and headings.
    route = route.replace('](acceptance/', '](../docs/acceptance/')
    for name in ('learner-route.md', 'capabilities.md', 'learner-cockpit.md', 'stock-route-research.json', 'learner-route-custom-legacy.md'):
        route = route.replace(']('+name+')', '](../docs/'+name+')')
    # Keep explicit ../codelab self-link, consistent with export path relocation.
    lines = []; fenced = False
    for line in route.splitlines():
        if line.startswith(chr(96)*3): fenced = not fenced
        if not fenced and line.startswith('#'):
            line = '### '+line.lstrip('#').lstrip()
        lines.append(line)
    route = '\n'.join(lines)+'\n'
    page = ROOT/'codelab/codelab.md'
    text = page.read_text()
    before, rest = text.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    return before+BEGIN+'\n\n'+route+'\n'+END+after
if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--write', action='store_true'); args = p.parse_args()
    dest = ROOT/'codelab/codelab.md'; expected = render()
    if args.write: dest.write_text(expected)
    elif dest.read_text() != expected: raise SystemExit('FAIL: codelab tutorial copy stale; run tools/tutorial_copy.py --write')
    print('PASS: canonical codelab tutorial copy current; no native execution')
